// 図のラベル配置の採点に使う罰点とすきま。採点の値は部品ごとに持たず、本モジュールに集める。線の切り
// 抜きの余白は描く部品の側に、候補の並びは候補の生成器の側に置く。

/** 配置の採点の定数。 */
export const LABEL_POLICY = {
  // 候補が配置の範囲から出たときの罰点。どの重なりの合計よりも重く、範囲の外の候補を実質的に捨てる。
  outside: 1000,
  // 既出のラベルと重なったときの罰点。
  labelOverlap: 10,
  // 矩形の障害物と既出のラベルに近いときの軽い罰点。
  near: 2,
  // ラベルどうしの間に残したいすきま（px）。隣り合う文字が 1 続きの式に見えるのを防ぐ。
  labelSpacing: 4,
  // 線の縁とラベルの間に残すすきま（px）。点の印とラベルの間のすきまも同じ値にする。
  lineClearance: 4,
  // 線の太さの半分の上限（px）。当たり判定は線の中心で行うので、線の縁からのすきまに直すために足す。
  lineHalfWidth: 1,
  // 字形の見積もりの誤差を吸収する余分のすきま（px）。字形は見積もりの外へ 1px 近くはみ出すことがある。
  glyphSlack: 1,
  // 線に触れるとみなす、線の中心とラベルの矩形の縁の距離の上限（px）。
  lineTouch: 1.5,
  // 線の重みのうち、線には触れないがすきまが足りないときに与える割合。すきまの足りない線が数本あっても、
  // 線を横切る候補より罰点が小さくなる値にする。
  nearLine: 0.25,
  // 曲線のラベルの、線の反対側の候補の罰点。線の進む向きの右側を先に試し、同点だけを分ける。
  otherSide: 0.05,
  // labelAt で線の上の点を決めた曲線のラベルの、線の反対側の候補の罰点。手前の側の罰点が反対側より
  // fixedSide より大きいときだけ側を変える。線が曲がると、箱の角が自分の線と境界線のすきまの帯（合計
  // 2.25）へ入るが、すきまの帯だけなら側を保つ。重みの軽い線に触れても側は変わらず、帯に入る線が増えると
  // 触れなくても変わる。
  fixedSide: 2.5,
  // 線の上のラベルに、同じ線の離れた部分が重なったときの罰点。
  ownLine: 6,
  // 線の切れ目の先に短い切れ端が残るとみなす、残りの弧長の上限（px）と、切れ端が残る候補の罰点。線の端や
  // 点の印の直前まで切れ目が伸びると、点のような切れ端が残って線の続きに見えない。候補を消さず、罰点
  // だけを与えるので、短い線のラベルも置ける。罰点は 2〜10 のどの値でも全ページの配置が同じである。線に
  // 触れる罰点（主役の線の重み 6）より軽くするため、範囲の下寄りの 3 にする。
  stubLength: 12,
  stub: 3,
  // 線の上のラベルが、先に置いたラベルに近いときの罰点の最大と、罰点が 0 になるすきま（px）。ラベルごとに
  // crowd × (1 − すきま / crowdRadius) を足す。閾値で急に切り替えると、すきまの小さな差で罰点が跳ぶので、
  // なめらかに減らす。同心円では同じくらい良い位置が複数あるので、半径の小さな差でもラベルは動く。最大の
  // 値は閉じた線の右上の好みの最大（2）と釣り合わせ、同心の等高線のラベルが同じ扇形に積み上がるのを防ぐ。
  crowd: 2,
  crowdRadius: 80,
} as const;

